import { createHash } from 'node:crypto'
import { readdir, readFile } from 'node:fs/promises'
import { Scrypt } from '@adonisjs/hash/drivers/scrypt'
import postgres from 'postgres'

export function connectDatabase() {
  const url = process.env.NUXT_DATABASE_URL || process.env.DATABASE_URL
  if (!url) throw new Error('Set DATABASE_URL in .env')
  return postgres(url, { max: 1, connect_timeout: 10, onnotice: () => {} })
}

export async function migrateDatabase(sql: postgres.Sql) {
  const directory = new URL('./migrations/', import.meta.url)
  const files = (await readdir(directory)).filter(name => name.endsWith('.sql')).sort()

  await sql.begin(async (transaction) => {
    await transaction`SELECT pg_advisory_xact_lock(748249154)`
    await transaction`
      CREATE TABLE IF NOT EXISTS schema_migrations (
        name text PRIMARY KEY,
        checksum text NOT NULL,
        applied_at timestamptz NOT NULL DEFAULT now()
      )
    `
    for (const name of files) {
      try {
        const source = (await readFile(new URL(name, directory), 'utf8')).replace(/\r\n/g, '\n')
        const checksum = createHash('sha256').update(source).digest('hex')
        const [applied] = await transaction`SELECT checksum FROM schema_migrations WHERE name = ${name}`
        if (applied) {
          if (applied.checksum !== checksum) {
            throw new Error(`Applied migration checksum mismatch (stored: ${applied.checksum}, current: ${checksum}). Restore the applied file and add a new migration for changes.`)
          }
          continue
        }
        await transaction.unsafe(source)
        await transaction`INSERT INTO schema_migrations (name, checksum) VALUES (${name}, ${checksum})`
      } catch (error) {
        throw new Error(`Migration failed: ${name}`, { cause: error })
      }
    }
  })
}

export async function ownerSeedCredentials(env: Record<string, string | undefined>) {
  const email = env.NUXT_OWNER_EMAIL?.trim().toLowerCase()
  const hash = env.NUXT_OWNER_PASSWORD_HASH
  const password = env.NUXT_OWNER_PASSWORD
  if (!email || email.length > 254 || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
    throw new Error('Set a valid NUXT_OWNER_EMAIL in .env')
  }
  if (hash && password) throw new Error('Set only one of NUXT_OWNER_PASSWORD_HASH or NUXT_OWNER_PASSWORD')
  const scrypt = new Scrypt({})
  if (hash) {
    if (!scrypt.isValidHash(hash)) throw new Error('NUXT_OWNER_PASSWORD_HASH must be a scrypt hash generated by bun run auth:hash')
    return { email, hash }
  }
  if (!password || password.length < 12 || password.length > 1024) {
    throw new Error('Set NUXT_OWNER_PASSWORD_HASH, or NUXT_OWNER_PASSWORD with 12–1024 characters, in .env')
  }
  return { email, hash: await scrypt.make(password), password }
}

export async function seedOwner(sql: postgres.Sql, credentials: { email: string, hash: string, password?: string }) {
  await sql.begin(async (transaction) => {
    await transaction`SELECT pg_advisory_xact_lock(748249155)`
    const [existing] = await transaction`SELECT password_hash FROM "user" WHERE id = 1 FOR UPDATE`
    let hash = credentials.hash
    if (existing && credentials.password
      && await new Scrypt({}).verify(existing.password_hash, credentials.password)) {
      hash = existing.password_hash
    }
    await transaction`
    INSERT INTO "user" (id, email, password_hash)
    VALUES (1, ${credentials.email}, ${hash})
    ON CONFLICT (id) DO UPDATE SET
      email = EXCLUDED.email,
      password_hash = EXCLUDED.password_hash,
      updated_at = now()
    WHERE "user".email IS DISTINCT FROM EXCLUDED.email
      OR "user".password_hash IS DISTINCT FROM EXCLUDED.password_hash
  `
  })
}
